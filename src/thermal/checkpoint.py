"""Checkpoint I/O with case and thermal-boundary compatibility checks."""
import hashlib
from pathlib import Path
import torch
from .model import AnalyticThermalModel
from .atsim import temperature_target


def metadata(params, system):
    binary = Path(params.thermal_solver)
    assets = binary.parent
    def digest(path):
        return hashlib.sha256(Path(path).read_bytes()).hexdigest()
    return {
        "format_version": 4,
        "solver": "ATSim",
        "temperature_target": temperature_target(assets / "structure.xml.template"),
        "mesh_mode": "single_tier_uniform_xy",
        "case": system.case_name,
        "interposer_um": [float(system.intp_width), float(system.intp_height)],
        "chiplets": list(system.node_names[:system.num_chiplets]),
        "widths_um": system.node_size_x[:system.num_chiplets].tolist(),
        "heights_um": system.node_size_y[:system.num_chiplets].tolist(),
        "power_w": system.powermap.tolist(),
        "grid": [int(params.num_grid_x), int(params.num_grid_y)],
        "ambient_c": float(params.ambient),
        "thermal_convection_resistance_K_per_W": float(params.thermal_convection_resistance),
        "atsim_config_sha256": digest(assets / "sim.config.template"),
        "atsim_structure_sha256": digest(assets / "structure.xml.template"),
        "atsim_material_sha256": digest(assets / "material.config.template"),
        "atsim_binary_sha256": digest(binary),
        "stack_generator_sha256": digest(Path(__file__).with_name("atsim.py")),
    }


def new_model(params, system):
    return AnalyticThermalModel(system.intp_width, system.intp_height,
        system.num_chiplets, params.num_grid_x, params.num_grid_y)


def check_metadata(actual, expected):
    if actual != expected:
        changed = sorted(k for k in set(actual) | set(expected) if actual.get(k) != expected.get(k))
        raise ValueError("Thermal model/dataset settings mismatch: " + ", ".join(changed) + ". Retrain for the current settings.")


def load_model(path, params, system):
    path = Path(path)
    if not path.is_file():
        raise FileNotFoundError(f"Thermal model not found: {path}. Generate it with run_thermal_training.py --case {system.case_name}.")
    saved = torch.load(path, map_location="cpu", weights_only=True)
    if not isinstance(saved, dict) or "metadata" not in saved or "state_dict" not in saved:
        raise ValueError("Expected a thermal checkpoint generated by run_thermal_training.py")
    check_metadata(saved["metadata"], metadata(params, system))
    model = new_model(params, system)
    model.load_state_dict(saved["state_dict"], strict=True)
    if not all(torch.isfinite(t).all() for t in model.state_dict().values()):
        raise ValueError("Thermal model contains non-finite values")
    model.to("cpu")
    model.eval().requires_grad_(False)
    return model
